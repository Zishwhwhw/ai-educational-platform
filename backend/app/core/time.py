"""Единая точка получения текущего времени.

`datetime.utcnow()` объявлен устаревшим и будет удалён: он возвращает время UTC,
но помечает его как наивное, из-за чего его легко случайно сравнить с локальным.

Здесь возвращается **наивное** время UTC осознанно: колонки объявлены как
`DateTime` без часового пояса, и подмешивание aware-значений привело бы к
`TypeError: can't compare offset-naive and offset-aware datetimes` в сравнениях.

Переход на `DateTime(timezone=True)` по всей схеме — отдельное решение: он
затрагивает 20+ колонок, миграцию и всю логику стриков, дневных лимитов
и античита. Делать его стоит вместе с переписыванием этой логики в фазе
центрального цикла, а не отдельным проходом.
"""

from datetime import UTC, datetime


def utcnow() -> datetime:
    """Текущее время UTC без указания зоны — под текущую схему БД."""
    return datetime.now(UTC).replace(tzinfo=None)
